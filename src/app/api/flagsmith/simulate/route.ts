import { NextResponse } from "next/server";
import { simulateTestTraffic } from "@/lib/flagsmith/experimentation-service";

export async function POST(request: Request) {
  try {
    const body = await request.json();
    const flag = body.featureFlagName || "checkout_experience";
    const count = Math.min(100, Math.max(1, body.count || 20));

    const simResult = await simulateTestTraffic(flag, count);

    return NextResponse.json({
      success: true,
      isSynthetic: true,
      trafficLabel: "Interactive Synthetic Telemetry",
      result: simResult,
      notice: "This data was generated by the test-traffic simulator and is explicitly flagged as synthetic.",
    });
  } catch (err: any) {
    return NextResponse.json({ error: err.message }, { status: 400 });
  }
}

